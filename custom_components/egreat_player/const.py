"""Constants for the Egreat Player integration."""

DOMAIN = "egreat_player"
CONF_PORT = "port"
CONF_BAUDRATE = "baudrate"

# 亿格瑞播放器RS-232控制指令集（十六进制）
# 状态查询指令（判断是不是亿格瑞播放器）
CMD_STATUS      = bytes([0x21, 0x01, 0x05, 0x02, 0x01, 0x34, 0x0D])

# 基础控制指令
CMD_POWER_ON    = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x34, 0x0D])
CMD_POWER_OFF   = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x35, 0x0D])
CMD_VOLUME_UP   = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x18, 0x0D])
CMD_VOLUME_DOWN = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x17, 0x0D])
CMD_MUTE        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x43, 0x0D])
CMD_PLAY        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x40, 0x0D])
CMD_PAUSE       = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x40, 0x0D])
CMD_STOP        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x41, 0x0D])
CMD_PREVIOUS    = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x16, 0x0D])
CMD_NEXT        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x19, 0x0D])

# 导航控制指令
CMD_UP          = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x0B, 0x0D])
CMD_DOWN        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x0E, 0x0D])
CMD_LEFT        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x10, 0x0D])
CMD_RIGHT       = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x11, 0x0D])
CMD_ENTER       = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x0D, 0x0D])
CMD_MENU        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x45, 0x0D])
CMD_BACK        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x42, 0x0D])
CMD_HOME        = bytes([0x21, 0x01, 0x08, 0x02, 0x19, 0x1A, 0x0D])